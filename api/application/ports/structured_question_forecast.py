"""Прогноз и оценщик получают разные возможности чтения данных."""
from typing import Protocol

class StructuredTrainingCorpus(Protocol):
    def context(self, reference: str) -> dict: ...
    def earlier_other_families(self, family: str, before: str) -> list[dict]: ...

class StructuredTargetOutcomes(Protocol):
    def outcome(self, reference: str) -> dict: ...

class StructuredForecastArtifacts(Protocol):
    def seal(self, run_id: str, value: dict) -> None: ...
    def read_seal(self, run_id: str) -> dict: ...
    def evaluate(self, run_id: str, evaluation_id: str, value: dict) -> None: ...
