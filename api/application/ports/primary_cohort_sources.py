"""Порты получения первичного материала; контроль доступен только как метаданные."""
from typing import Protocol


class PrimarySourceProvider(Protocol):
    def metadata(self, doi: str) -> dict: ...
    def training_xml(self, entry: dict, record: dict) -> str: ...
    def control_candidates(self) -> list[dict]: ...


class PrimarySourceStore(Protocol):
    def read(self, entry: dict) -> dict | None: ...
    def save(self, entry: dict, result: dict, xml: str | None, text: str | None) -> None: ...
