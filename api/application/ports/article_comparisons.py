"""Порты чтения конкретных запусков и неизменяемого хранения сравнения."""
from typing import Protocol


class ComparisonMaps(Protocol):
    def get(self, article_id: str, pipeline_id: str, user_uid: str, run_id: str): ...
    def authorize(self, article_id: str, user_uid: str): ...


class ComparisonRepository(Protocol):
    def get(self, comparison_id: str, user_uid: str): ...
    def save(self, result: dict, user_uid: str): ...
    def list(self, user_uid: str, article_id: str | None = None): ...
    def pairs(self, comparison_id: str, user_uid: str, **filters): ...


class ComparisonControls(Protocol):
    def select(self, references: list[dict]) -> dict: ...
