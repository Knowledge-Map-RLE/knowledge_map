"""Порты корпуса и неизменяемых результатов не включают модельные клиенты."""
from typing import Protocol
from domain.empirical_question_forecast import Observation

class ExplicitEmpiricalCorpus(Protocol):
    def read(self, references: list[str]) -> list[Observation]: ...

class EmpiricalForecastArtifacts(Protocol):
    def seal(self, run_id: str, artifact: dict) -> None: ...
    def read_seal(self, run_id: str) -> dict: ...
    def evaluate(self, run_id: str, evaluation_id: str, artifact: dict) -> None: ...
