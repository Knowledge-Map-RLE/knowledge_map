"""Порты прогноза по вопросу не содержат генерацию моделей."""
from typing import Protocol


class ResearchMaps(Protocol):
    def get(self, article_id: str, pipeline_id: str, user_uid: str, run_id: str): ...
    def authorize(self, article_id: str, user_uid: str): ...


class QuestionForecastStore(Protocol):
    def read_seal(self, run_id: str): ...
    def seal(self, run_id: str, artifact: dict): ...
    def save_evaluation(self, run_id: str, evaluation_id: str, result: dict): ...


class ResearchArtifacts(Protocol):
    def audit(self, artifact_id: str, artifact: dict): ...
