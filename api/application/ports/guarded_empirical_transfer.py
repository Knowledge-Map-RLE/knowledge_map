"""Порты изолированной фиксации и оценки переноса."""
from typing import Protocol


class TransferCorpus(Protocol):
    def training(self) -> dict: ...
    def requests(self) -> dict: ...
    def outcomes(self) -> dict: ...


class TransferStore(Protocol):
    def seal(self, run_id: str, artifact: dict) -> None: ...
    def read_seal(self, run_id: str) -> dict: ...
    def evaluate(self, run_id: str, evaluation_id: str, artifact: dict) -> None: ...
