"""Раздельные порты источников, доступных предпосылок и скрытых выводов оценщика."""
from typing import Protocol


class OperatorCorpus(Protocol):
    def training(self, references: list[str]): ...
    def premises(self, reference: str): ...
    def outcomes(self, reference: str): ...


class OperatorForecastStore(Protocol):
    def read_seal(self, run_id: str): ...
    def seal(self, run_id: str, artifact: dict): ...
    def save_evaluation(self, run_id: str, evaluation_id: str, result: dict): ...
