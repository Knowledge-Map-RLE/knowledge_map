"""Двуязычный автономный отчёт о том, что определяют опубликованные наблюдения."""
import argparse
import json
from pathlib import Path
from infrastructure.observation_identifiability import FileObservationAuditStore
from infrastructure.immutable_files import write_immutable
from domain.article_maps import require

def main():
    p=argparse.ArgumentParser();p.add_argument('--root',required=True);p.add_argument('--run-id',required=True);args=p.parse_args()
    root=Path(args.root).resolve();store=FileObservationAuditStore(root/'runs');data=store.read(args.run_id)
    require(data is not None,'Sealed audit required')
    template=(Path(__file__).resolve().parents[1]/'infrastructure/observation_report.html').read_text(encoding='utf-8')
    payload=json.dumps(data,ensure_ascii=False,sort_keys=True).replace('<','\\u003c').replace('&','\\u0026')
    review=root/'review-v1';write_immutable(review/'data.json',store.encode(data))
    write_immutable(review/'report.html',template.replace('__DATA__',payload).encode('utf-8'))
    report=f'''# Данные наблюдений и длительность MCI

Проверены методы семи сохранённых статей и таблица 3 PAQUID. Новых подтверждённых научных знаний и эмпирических прогнозов: **0**.

## Что удалось установить

| Источник | Опубликованное расписание |
|---|---|
| Busse 2003 | Через 18 и 36 месяцев после исходного визита |
| Caracciolo 2008 | Примерно три года; интервалы 3,4±0,5, 2,9±0,9, 2,8±0,5 года |
| Katz 2012 | Последующие очные осмотры с интервалом 12 месяцев |
| Larrieu 2002 | Анализ визитов 1993, 1995, 1998 годов: интервалы два и три года |
| Luck 2010 | Пять последующих осмотров за восемь лет, в среднем через 1,4 года |
| Manly 2008 | Аннотация: 18–24 месяца; методы: 18–30 месяцев; среднее 24,3 месяца, SD 6,4 |
| Roberts 2012 | Визиты с интервалом 15 месяцев |

Плановое расписание не доказывает точные индивидуальные интервалы. Среднее время между визитами не является длительностью MCI. Расхождение описаний WHICAP сохранено; не выбирается удобная цифра.

## Что означает таблица PAQUID

Из 58 исходных случаев MCI на визите через два года MCI наблюдали у 4 (6,9%), нормальное состояние — у 24 (41,4%). Среди 37 случаев MCI на двухлетнем визите через следующие три года MCI наблюдали у 2 (5,4%), нормальное состояние — у 16 (43,2%). Остальные состояния, смерть и пропуски сохранены отдельно. Таблица визуально сверена с PDF, страница 4, печатная страница 1597.

Это состояние на следующем визите, не вероятность непрерывно оставаться в MCI. Две строки относятся к разным наборам распространённых случаев; их нельзя перемножать как выживание одного эпизода. Проценты сохранены как напечатаны: они не нормализуются и отсутствующие целые числа не восстанавливаются по округлению. Стратификации длительности по образованию эта таблица не даёт.

## Конструктивная проверка ограничения

Вымышленные истории с идеальной диагностикой и визитами в 0, 2 и 5 лет:

- Эпизод от 1,9 до 2,1 года: длительность 0,2 года.
- Эпизод от 0,1 до 4,9 года: длительность 4,8 года.
- К первому эпизоду можно добавить невидимый эпизод от 0,5 до 0,75 года.

Все три дают одинаковые состояния на визитах: **норма → MCI → норма**. Можно назначить длинный эпизод группе высокого образования, а короткий — низкого, или наоборот; посещения не отличат эти миры. Это математические свидетели неидентифицируемости, не реконструкция пациентов.

Даже при одном непрерывном эпизоде такая последовательность ограничивает полную длительность лишь открытым интервалом (0,5) лет. Если MCI есть уже исходно, его начало цензурировано слева: исчезновение к двухлетнему визиту не означает, что полная длительность не больше двух лет. При MCI на двух последовательных визитах возможны как непрерывный эпизод, так и возврат к норме и новый эпизод между ними.

## Что добавить в скрытую семантику

До применения операторов различать измеряемую величину, наблюдательный процесс, вид цензурирования, условность реконструкции, выбранные предположения и идентифицируемость. Операторы сравнения и прогноза не должны подменять длительность эпизода интервалом наблюдения или устойчивость состояния на визитах — выживанием одного эпизода. Этот экспериментальный проверяющий модуль добавлен отдельно; production-пайплайн и карты пока не изменены.

## Следующий шаг

Нужны индивидуальные времена визитов и состояния, группы образования, границы начала/исчезновения, пропуски и смерть, качество диагностики. Затем отдельно зафиксировать допущения о возвратах и длительности; проверить устойчивость вывода к допустимым скрытым историям. Если направление различается между ними, прогноз должен быть неопределённым. Другая возможность — выбрать оператор, для которого опубликованных измерений уже достаточно.

## Проверка и границы

Это ретроспективный аудит ранее прочитанных источников. Происхождение сохранено координатами Unicode code points и хешами полных текстов. Полноценная экспертная проверка отсутствует. Никакие провайдерские или локальные модели, эмбеддинги и переводчики не вызваны; сеть в CLI отключена. Новые контрольные статьи не открывались. Данные старого механистического опыта, GOLD, Neo4j и сервисы не менялись.

Запуск: `{args.run_id}`.
'''
    write_immutable(review/'report.ru.md',report.encode('utf-8'))
    print(json.dumps({'report':str(review/'report.html'),'scientific_success':False}))

if __name__=='__main__':main()
